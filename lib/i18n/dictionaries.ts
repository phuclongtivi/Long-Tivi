export const dictionaries: Record<Locale, Dict> = { vi, en, zh };

export function t(locale: Locale, key: string): string {
  return dictionaries[locale]?.[key] ?? dictionaries.vi[key] ?? key;
}

export function formatT(locale: Locale, key: string, vars: Record<string, string | number>): string {
  return t(locale, key).replace(/\{(\w+)\}/g, (_, name: string) =>
    vars[name] == null ? `{${name}}` : String(vars[name])
  );
}
